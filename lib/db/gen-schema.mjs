// Embeds src/schema.sql into src/schema.generated.ts so a bundled server needs no loose files.
// Run after editing schema.sql:  node lib/db/gen-schema.mjs   (CI checks the result is committed)
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("./src/", import.meta.url);
const sql = readFileSync(new URL("schema.sql", dir), "utf8");
writeFileSync(new URL("schema.generated.ts", dir), `// GENERATED by gen-schema.mjs from schema.sql. Do not edit.\nexport const SCHEMA_SQL = ${JSON.stringify(sql)};\n`);
